"""Encode Unicode text to GBK bytes.

CP936 (the code page Windows calls GBK) extends the original GBK standard with
roughly 80 Private Use Area (PUA) code points, mainly in the U+E000..U+E4C5
range. Those code points are what Windows produces when it decodes a GBK byte
pair that the original standard left unmapped. Python's ``gbk`` codec rejects
them, so round-tripping text that came from a Windows GBK source requires an
explicit mapping.

The table below is deliberately a plain dict rather than a codec. Registering a
new codec would make the mapping global and could surprise unrelated code; a
function that takes a table is easier to test and to reason about.
"""


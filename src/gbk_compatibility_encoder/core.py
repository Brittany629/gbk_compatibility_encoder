def is_pua_extension(code_point: int) -> bool:
    """Return True if ``code_point`` is in the CP936 PUA extension table."""

    return code_point in PUA_TABLE


def encode_char(code_point: int) -> Optional[EncodedChar]:
    """Encode a single code point to GBK bytes.

    Returns ``None`` for code points that neither the standard GBK codec nor
    the PUA extension table can represent. Surrogates and negative values are
    rejected outright rather than passed to ``chr`` (which would raise).
    """

    if not isinstance(code_point, int):
        raise TypeError("code_point must be an int")
    if code_point < 0 or code_point > 0x10FFFF:
        return None
    if 0xD800 <= code_point <= 0xDFFF:
        return None

    if code_point in PUA_TABLE:
        return EncodedChar(PUA_TABLE[code_point], True)

    try:
        data = chr(code_point).encode("gbk")
    except UnicodeEncodeError:
        return None
    return EncodedChar(data, False)


def encode_string(text: str) -> bytes:
    """Encode ``text`` to GBK, using the PUA table for unmapped code points.

    The standard ``gbk`` codec is tried first for the whole string; only when
    it fails do we fall back to per-character encoding. This keeps the common
    path fast and avoids surprising differences for text the codec already
    handles.

    Raises ``UnicodeEncodeError`` for code points that neither path can map.
    """

    if not isinstance(text, str):
        raise TypeError("text must be a str")

    try:
        return text.encode("gbk")
    except UnicodeEncodeError:
        pass

    out: List[bytes] = []
    for index, ch in enumerate(text):
        encoded = encode_char(ord(ch))
        if encoded is None:
            raise UnicodeEncodeError(
                "gbk_compatibility_encoder",
                text,
                index,
                index + 1,
                "character not representable in GBK or the CP936 PUA extension",
            )
        out.append(encoded.data)
    return b"".join(out)
